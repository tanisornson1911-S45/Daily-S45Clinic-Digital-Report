#!/usr/bin/env node
/**
 * build-consult-pipeline.mjs
 * ---------------------------------------------------------------
 * Transforms the "ปรึกษา 2026" sheet (src/data/m365Raw.json, refreshed daily
 * by scripts/fetch-m365-data.mjs) into src/data/consultPipeline.json — the
 * quoted "Online price" value of leads that have consulted but NOT yet put
 * down a deposit (still pure pipeline, not a realized sale).
 *
 * Per user request: "ยอดขายรวม (Facebook)" on the Overview page should equal
 * Online Price (from this sheet, consult-only rows) + Total Price (from
 * มัดจำ 2026 / RAW_TX, already-deposited rows) — NOT both sheets summed
 * unconditionally, because "ปรึกษา 2026" also contains rows for cases that
 * already progressed to deposit (status "มัดจำ", "ปรึกษา / Consult มัดจำ",
 * etc.) — those already have a matching RAW_TX row counted via Total Price,
 * so summing their Online Price too would double-count the same case.
 *
 * A row only qualifies as still-pipeline if its "ปรึกษา / มัดจำ" status
 * column is EXACTLY "ปรึกษา" or "ปรึกษาออนไลน์" (checked: every such row has
 * a blank Deposit column too, confirming no deposit has landed yet) — any
 * status mentioning "มัดจำ" is excluded.
 *
 * Uses "Date ปิด" (the date the consultation itself was closed/concluded) as
 * the entry date — populated on every qualifying row, unlike "Date ทักเข้า"
 * (initial contact date) which is sometimes blank.
 *
 * Run manually:
 *   node scripts/build-consult-pipeline.mjs
 *
 * Run automatically: see .github/workflows/update-m365-data.yml
 * ---------------------------------------------------------------
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const PIPELINE_STATUSES = new Set(["ปรึกษา", "ปรึกษาออนไลน์"]);

// เดียวกับแนวทางใน build-or-sales.mjs — หัตถการที่ไม่ตรงหมวดหลัก 4 หมวด บักเก็ตเป็น "other" แทนการดร็อปทิ้ง
const SURGERY_MAP = {
  "nose open": "nose_open",
  "semi open": "nose_semi",
  "breast": "breast_lipo",
  "ดูดไขมัน": "breast_lipo",
  "brow lift": "brow_hairline",
  "เลื่อนไรผม": "brow_hairline",
  "ดึงหน้า": "brow_hairline",
};
function mapSurgery(raw) {
  return SURGERY_MAP[String(raw || "").trim().toLowerCase()] || "other";
}

function excelDate(s) {
  if (typeof s !== "number") return null;
  const dt = new Date(Math.round((s - 25569) * 86400 * 1000));
  return dt.toISOString().slice(0, 10);
}

function findCol(header, test) {
  return header.findIndex((h) => typeof h === "string" && test(h.trim()));
}

function main() {
  const m365Path = path.resolve("src/data/m365Raw.json");
  const m365 = JSON.parse(readFileSync(m365Path, "utf8"));
  const sheets = m365.workbooks?.data_s45_clinic;
  if (!sheets) {
    console.error('Could not find "data_s45_clinic" workbook in src/data/m365Raw.json.');
    process.exit(1);
  }
  const sheet = sheets["ปรึกษา 2026"];
  if (!sheet) {
    console.error('Sheet "ปรึกษา 2026" not found in src/data/m365Raw.json.');
    process.exit(1);
  }

  const header = sheet[0];
  const statusCol = findCol(header, (h) => h === "ปรึกษา / มัดจำ");
  const platformCol = findCol(header, (h) => h.toLowerCase().startsWith("platform"));
  const closeDateCol = findCol(header, (h) => h === "Date ปิด");
  const onlinePriceCol = findCol(header, (h) => h === "Online price");
  const depositCol = findCol(header, (h) => h === "Deposit");
  const surgeryCol = findCol(header, (h) => h.toLowerCase().startsWith("surgery"));

  const entries = [];
  let skippedNoDate = 0;
  for (const r of sheet.slice(1)) {
    if (!r.some((c) => c !== "" && c != null)) continue;
    const status = r[statusCol];
    if (!PIPELINE_STATUSES.has(status)) continue; // มัดจำแล้ว/สถานะอื่น — มีแถวคู่ใน RAW_TX นับ Total Price อยู่แล้ว
    if (r[depositCol] !== "" && r[depositCol] != null) continue; // กันเผื่อ: ถ้ามี Deposit จริงๆ ไม่ใช่ pipeline ล้วน
    const price = r[onlinePriceCol];
    if (typeof price !== "number" || price <= 0) continue;
    const d = excelDate(r[closeDateCol]);
    if (!d) {
      skippedNoDate++;
      continue;
    }
    entries.push({ d, platform: r[platformCol] || null, proc: mapSurgery(r[surgeryCol]), amount: price });
  }

  entries.sort((a, b) => (a.d < b.d ? -1 : a.d > b.d ? 1 : 0));

  const outPath = path.resolve("src/data/consultPipeline.json");
  writeFileSync(
    outPath,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        source:
          'Generated by scripts/build-consult-pipeline.mjs from the "ปรึกษา 2026" sheet in ' +
          '"Data S45 Clinic (5).xlsx" — Online Price of leads still at pure-consult status ' +
          '("ปรึกษา"/"ปรึกษาออนไลน์"), excluding anything that already progressed to a deposit ' +
          "(those are already counted via RAW_TX's Total Price).",
        entries,
      },
      null,
      2
    )
  );
  console.log(`Wrote ${outPath} (${entries.length} entries, ${skippedNoDate} skipped for no close date)`);
}

main();
