#!/usr/bin/env node
/**
 * fetch-fb-spend.mjs
 * ---------------------------------------------------------------
 * Pulls real monthly ad spend from the Facebook Marketing API for
 * the S45 Clinic ad accounts and writes it to src/data/adSpend.json.
 *
 * Run manually:
 *   FB_ACCESS_TOKEN=xxxx node scripts/fetch-fb-spend.mjs
 *
 * Run automatically: see .github/workflows/update-dashboard-data.yml
 *
 * Requires a System User access token with ads_read permission on
 * business "เสริมจมูกเกาหลี By หมอตี๋" (business_id 998717160298356).
 * Generate one at https://business.facebook.com/settings/system-users
 * and store it as the FB_ACCESS_TOKEN repo secret in GitHub
 * (Settings → Secrets and variables → Actions → New repository secret).
 * ---------------------------------------------------------------
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const SOURCE_NOTE =
  "Generated by scripts/fetch-fb-spend.mjs (Facebook Marketing API, account-level insights). " +
  "Each run pulls the last 10 months (9 full months back + month-to-date) and merges them into " +
  "whatever was already on disk — older months outside that window are preserved from the previous " +
  "run, not dropped, so history doesn't shrink as the rolling window moves forward. " +
  "'nose_open' = Nose Open 01 + 02 + the Freelance Nett account (221741759556998, added 2026-08-26 " +
  "after the team flagged it was missing — checked its full campaign list and none are named " +
  "\"Inter\", so its entire spend is pure nose_open). 'inter' = the dedicated Inter account " +
  "(1711014813661620, renamed from Nose Open 03 on 2026-08-06) plus any campaigns still named " +
  "\"Inter\" inside Nose Open 02 from before that reorg. 'total' = all 6 accounts in ACCOUNTS below " +
  "(nose_open x3 + semi + breast + brow) + the dedicated Inter account, 7 accounts total — not the " +
  "sum of the category fields, which would double-count the legacy Inter campaigns already inside " +
  "nose_open.";

const FB_ACCESS_TOKEN = process.env.FB_ACCESS_TOKEN;
const API_VERSION = "v21.0";

if (!FB_ACCESS_TOKEN) {
  console.error("Missing FB_ACCESS_TOKEN environment variable.");
  process.exit(1);
}

// S45 ad accounts -> dashboard category key
// (IDs confirmed live via Facebook Ads MCP on 2026-07-12)
// NOTE: account 1711014813661620 was "Nose Open 03" on 2026-07-12 but had been
// renamed to "S45 - Inter" by 2026-08-06 — the team repurposed it into a
// dedicated Inter account instead of tagging individual campaigns inside Nose
// Open 02. It is therefore EXCLUDED from the nose_open bucket below and its
// full spend is added to `inter` instead (see INTER_DEDICATED_ACCOUNT_ID).
// nose_open_freelance (221741759556998, "S45 - | Nose Open | Freelance Nett")
// added 2026-08-26 — the team flagged it was missing; checked its full
// campaign list Jun-Aug and none are named "Inter", so it's pure nose_open
// with no special-casing needed (unlike nose_open_02's legacy campaigns).
const ACCOUNTS = {
  nose_open_01: { id: "2214227468912072", category: "nose_open" },
  nose_open_02: { id: "1117617719803706", category: "nose_open" },
  nose_open_freelance: { id: "221741759556998", category: "nose_open" },
  semi_open: { id: "983591777378317", category: "nose_semi" },
  breast: { id: "1948728392195994", category: "breast_lipo" },
  brow_facelift: { id: "225618075", category: "brow_hairline" },
};

// "Inter" spend = the dedicated Inter ad account (renamed from Nose Open 03,
// confirmed 2026-08-06) PLUS any leftover campaigns inside Nose Open 02 whose
// name still contains "Inter" from before the reorg (confirmed 2026-07-12).
const INTER_DEDICATED_ACCOUNT_ID = "1711014813661620";
const INTER_CAMPAIGN_SEARCH_ACCOUNT_ID = "1117617719803706"; // Nose Open 02
const INTER_NAME_MATCH = /inter/i;

async function fetchInterCampaignSpend(accountId, since, until) {
  const url = new URL(`https://graph.facebook.com/${API_VERSION}/act_${accountId}/insights`);
  url.searchParams.set("level", "campaign");
  url.searchParams.set("fields", "campaign_name,spend");
  url.searchParams.set("time_range", JSON.stringify({ since, until }));
  url.searchParams.set("limit", "200");
  url.searchParams.set("access_token", FB_ACCESS_TOKEN);

  const res = await fetch(url);
  const json = await res.json();
  if (json.error) {
    console.error(`  ! Inter campaigns (${accountId}): ${json.error.message}`);
    return 0;
  }
  const rows = json.data || [];
  const matched = rows.filter((r) => INTER_NAME_MATCH.test(r.campaign_name || ""));
  const total = matched.reduce((sum, r) => sum + (r.spend ? parseFloat(r.spend) : 0), 0);
  console.log(`  Inter campaigns matched: ${matched.length} (of ${rows.length} in account)`);
  return Math.round(total);
}

function monthRange(year, month /* 1-12 */) {
  const since = `${year}-${String(month).padStart(2, "0")}-01`;
  const lastDay = new Date(year, month, 0).getDate();
  const until = `${year}-${String(month).padStart(2, "0")}-${String(lastDay).padStart(2, "0")}`;
  return { since, until };
}

async function fetchAccountSpend(accountId, since, until) {
  const url = new URL(`https://graph.facebook.com/${API_VERSION}/act_${accountId}/insights`);
  url.searchParams.set("fields", "spend");
  url.searchParams.set("time_range", JSON.stringify({ since, until }));
  url.searchParams.set("access_token", FB_ACCESS_TOKEN);

  const res = await fetch(url);
  const json = await res.json();
  if (json.error) {
    console.error(`  ! ${accountId}: ${json.error.message}`);
    return 0;
  }
  const spend = json.data?.[0]?.spend;
  return spend ? Math.round(parseFloat(spend)) : 0;
}

async function main() {
  const now = new Date();
  // Pull the last 9 full months plus month-to-date (10 months total).
  const months = [];
  for (let i = 9; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    months.push({ year: d.getFullYear(), month: d.getMonth() + 1 });
  }

  // Merge into whatever's already on disk instead of overwriting it — the
  // rolling 10-month window would otherwise permanently drop older months
  // (e.g. 2025-10) from the file a little more each time it runs.
  const outDir = path.resolve("src/data");
  const outPath = path.join(outDir, "adSpend.json");
  let result = {};
  try {
    const existing = JSON.parse(await readFile(outPath, "utf8"));
    result = existing.months || {};
  } catch {
    // No existing file (first run) — start from an empty object.
  }

  for (const { year, month } of months) {
    const { since, until } = monthRange(year, month);
    const key = `${year}-${String(month).padStart(2, "0")}`;
    console.log(`Fetching ${key} (${since} → ${until})...`);
    result[key] = {};

    let accountsTotal = 0;
    for (const [name, { id, category }] of Object.entries(ACCOUNTS)) {
      const spend = await fetchAccountSpend(id, since, until);
      result[key][category] = (result[key][category] || 0) + spend;
      accountsTotal += spend;
      console.log(`  ${name} (${category}): ฿${spend.toLocaleString()}`);
    }

    const interDedicatedSpend = await fetchAccountSpend(INTER_DEDICATED_ACCOUNT_ID, since, until);
    const interCampaignSpend = await fetchInterCampaignSpend(INTER_CAMPAIGN_SEARCH_ACCOUNT_ID, since, until);
    const interSpend = interDedicatedSpend + interCampaignSpend;
    result[key].inter = interSpend;
    console.log(`  inter (dedicated account ฿${interDedicatedSpend.toLocaleString()} + legacy "Inter" campaigns in Nose Open 02 ฿${interCampaignSpend.toLocaleString()}): ฿${interSpend.toLocaleString()}`);

    // Store an explicit month 'total' = sum of the 5 nose/semi/breast/brow accounts
    // plus the dedicated Inter account, which the dashboard's liveMonthTotal()
    // prefers over summing the breakdown fields.
    result[key].total = accountsTotal + interDedicatedSpend;
    console.log(`  total: ฿${result[key].total.toLocaleString()}`);
  }

  await mkdir(outDir, { recursive: true });
  await writeFile(
    outPath,
    JSON.stringify({ generatedAt: now.toISOString(), source: SOURCE_NOTE, months: result }, null, 2)
  );
  console.log(`\nWrote ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
